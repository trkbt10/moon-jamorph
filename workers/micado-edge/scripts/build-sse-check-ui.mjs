#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const workerDir = resolve(scriptDir, "..");
const sourceDir = resolve(workerDir, "src", "ui", "sse-check");
const generatedDir = resolve(workerDir, "src", "ui", "generated");
const cacheDir = resolve(workerDir, ".cache", "ui");

const sourceHtmlPath = resolve(sourceDir, "index.html");
const sourceJsPath = resolve(sourceDir, "main.js");
const bundledJsPath = resolve(cacheDir, "sse-check.bundle.js");
const generatedModulePath = resolve(generatedDir, "sse-check-ui.mjs");

function replaceScriptTag(html, inlineJs) {
  const scriptTag = '<script type="module" src="./main.js"></script>';
  const safeJs = inlineJs.replace(/<\/script/gi, "<\\/script");
  const replacement = `<script type="module">\n${safeJs}\n</script>`;
  if (!html.includes(scriptTag)) {
    throw new Error(`script tag not found in ${sourceHtmlPath}`);
  }
  return html.replace(scriptTag, replacement);
}

function runBunBuild() {
  const build = spawnSync(
    "bun",
    [
      "build",
      sourceJsPath,
      "--target=browser",
      "--minify",
      "--sourcemap=none",
      "--outfile",
      bundledJsPath,
    ],
    {
      cwd: workerDir,
      encoding: "utf8",
      env: process.env,
    },
  );

  if (build.status !== 0) {
    const stdout = build.stdout?.trim() ?? "";
    const stderr = build.stderr?.trim() ?? "";
    throw new Error(`bun build failed\n${stdout}\n${stderr}`.trim());
  }
}

async function main() {
  await mkdir(cacheDir, { recursive: true });
  await mkdir(generatedDir, { recursive: true });

  runBunBuild();

  const [sourceHtml, bundledJs] = await Promise.all([
    readFile(sourceHtmlPath, "utf8"),
    readFile(bundledJsPath, "utf8"),
  ]);

  const finalHtml = replaceScriptTag(sourceHtml, bundledJs);
  const output = `// generated by scripts/build-sse-check-ui.mjs\nexport const SSE_CHECK_UI = ${JSON.stringify(finalHtml)};\n`;
  await writeFile(generatedModulePath, output, "utf8");

  console.log(`[build-sse-ui] source html: ${sourceHtmlPath}`);
  console.log(`[build-sse-ui] source js: ${sourceJsPath}`);
  console.log(`[build-sse-ui] generated: ${generatedModulePath}`);
}

main().catch((error) => {
  console.error(`[build-sse-ui] ${error?.stack ?? error}`);
  process.exit(1);
});
